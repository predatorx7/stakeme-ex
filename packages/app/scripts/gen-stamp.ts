import assert from 'node:assert'
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { parse } from 'yaml'

export type GenStamp = {
	specVersion: string
	sourceHash: string
}

/**
 * Compute the drift stamp for `openapi.yaml`: its declared `info.version`,
 * plus a truncated SHA-256 of the exact bytes the generators read.
 *
 * The hash is what actually catches drift. `info.version` is hand-maintained,
 * so a spec can change materially — a new field, a tightened constraint, a
 * whole new operation — with nobody remembering to bump it, and a stale
 * checked-in generated file would then still show a "current" version. Never
 * drop the hash thinking the version makes it redundant; the version alone
 * under-detects drift.
 */
export async function computeGenStamp(specPath: string): Promise<GenStamp> {
	const raw = await readFile(specPath)
	const sourceHash = createHash('sha256').update(raw).digest('hex').slice(0, 12)

	const spec = parse(raw.toString('utf8')) as { info?: { version?: unknown } }
	const specVersion = spec?.info?.version
	assert(
		typeof specVersion === 'string' && specVersion.length > 0,
		`${specPath}: expected a string "info.version"`,
	)

	return { specVersion, sourceHash }
}

/**
 * Render the header lines every OpenAPI-derived generated file carries,
 * stamped with the spec version + content hash it was generated from.
 * `generatorRelPath` is the script that produced the file, `npmScript` the
 * command to regenerate it.
 */
export function renderStampHeader(opts: {
	generatorRelPath: string
	npmScript: string
	stamp: GenStamp
}): string[] {
	const { generatorRelPath, npmScript, stamp } = opts
	return [
		`// AUTO-GENERATED by ${generatorRelPath}`,
		'// from packages/app/openapi.yaml ' +
			`(spec v${stamp.specVersion}, source sha256:${stamp.sourceHash}).`,
		'// The hash catches drift the version misses (a spec can change without a',
		'// version bump) — do not remove it as "redundant" with the version.',
		`// Run \`${npmScript}\` to regenerate. Do not edit by hand.`,
	]
}

const STAMP_RE = /spec v(?<version>\S+), source sha256:(?<hash>[0-9a-f]{12})\)/

/**
 * Pull a previously rendered stamp back out of a generated file's header, for
 * the drift check in `check-gen.ts`. Returns `null` if the file has no stamp
 * (for example, it predates this scheme, or was hand-edited).
 */
export function parseStampFromHeader(contents: string): GenStamp | null {
	const match = STAMP_RE.exec(contents)
	if(!match?.groups) {
		return null
	}

	return { specVersion: match.groups.version, sourceHash: match.groups.hash }
}
