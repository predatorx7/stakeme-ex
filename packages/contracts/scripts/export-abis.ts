// Writes src/abis.gen.ts (as-const ABIs) and src/deployments.gen.ts.
// Run with `npm run abis` after `hardhat compile`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const names = [
	'LiquidISA',
	'LiquidISAFactory',
	'CreatorShareToken',
	'MockUSDC',
] as const

let abis = '// Generated by scripts/export-abis.ts. Do not edit.\n\n'
for(const name of names) {
	const file = join(root, 'artifacts/contracts', `${name}.sol`, `${name}.json`)
	if(!existsSync(file)) {
		throw new Error(`Missing artifact ${file}. Run \`hardhat compile\` first.`)
	}

	const { abi } = JSON.parse(readFileSync(file, 'utf8'))
	abis += `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, '\t')} as const;\n\n`
}

writeFileSync(join(root, 'src/abis.gen.ts'), abis.trimEnd() + '\n')

// Ignition: ignition/deployments/chain-<id>/deployed_addresses.json
const deployments: Record<string, Record<string, string>> = {}
const dir = join(root, 'ignition/deployments')
if(existsSync(dir)) {
	for(const entry of readdirSync(dir)) {
		const file = join(dir, entry, 'deployed_addresses.json')
		const id = entry.match(/^chain-(\d+)$/)?.[1]
		if(!id || !existsSync(file)) {
			continue
		}

		const raw: Record<string, string> = JSON.parse(readFileSync(file, 'utf8'))
		deployments[id] = Object.fromEntries(
			Object.entries(raw).map(([k, v]) => [k.split('#')[1] ?? k, v]),
		)
	}
}

writeFileSync(
	join(root, 'src/deployments.gen.ts'),
	'// Generated by scripts/export-abis.ts. Do not edit.\n\n' +
		`export const deployments: Record<string, Record<string, string>> = ${JSON.stringify(deployments, null, '\t')};\n`,
)
console.log(`Exported ${names.length} ABIs and ${Object.keys(deployments).length} deployment(s).`)
